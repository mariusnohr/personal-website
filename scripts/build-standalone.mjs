/**
 * Build a self-contained deployment artifact for the hosting platform.
 *
 * The platform's "app" pipeline stages and runs a Next.js style standalone
 * bundle: it expects a `.next/standalone` directory containing a `server.js`
 * entry point and fails the deploy otherwise. This project is intentionally
 * a Vite + TypeScript client, so after `vite build` has produced `dist/` we
 * wrap that output in the expected shape:
 *
 *   .next/standalone/
 *     server.js     -> dependency-free static server for `dist/`
 *     package.json  -> marks the folder as CommonJS
 *     dist/         -> the Vite build output
 *
 * The generated server is fully self-contained because only the
 * `.next/standalone` directory is uploaded to the server; the project's
 * `node_modules` are not.
 */
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const distDir = resolve(root, 'dist');
const standaloneDir = resolve(root, '.next/standalone');
const standaloneDist = resolve(standaloneDir, 'dist');

if (!existsSync(resolve(distDir, 'index.html'))) {
  throw new Error(
    'dist/index.html not found. Run the client build before this script.',
  );
}

/** A small, dependency-free static file server with SPA fallback. */
const serverSource = `// Generated by scripts/build-standalone.mjs. Do not edit by hand.
'use strict';

var http = require('node:http');
var fs = require('node:fs');
var path = require('node:path');

var root = path.join(__dirname, 'dist');
var layout = path.join(root, 'index.html');
var port = Number(process.env.PORT) || 3000;
var hostname = process.env.HOSTNAME || '0.0.0.0';

var MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
  '.xml': 'application/xml',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.avif': 'image/avif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.otf': 'font/otf',
  '.txt': 'text/plain; charset=utf-8',
  '.wasm': 'application/wasm',
};

function sendFile(req, res, filePath) {
  var type = MIME_TYPES[path.extname(filePath).toLowerCase()] || 'application/octet-stream';
  res.writeHead(200, { 'Content-Type': type });
  if (req.method === 'HEAD') {
    res.end();
    return;
  }
  fs.createReadStream(filePath).on('error', function () {
    res.destroy();
  }).pipe(res);
}

function resolvePath(requestUrl) {
  var pathname;
  try {
    pathname = decodeURIComponent(new URL(requestUrl, 'http://localhost').pathname);
  } catch (err) {
    return null;
  }
  var resolved = path.normalize(path.join(root, pathname));
  if (resolved !== root && resolved.indexOf(root + path.sep) !== 0) {
    return null;
  }
  return resolved;
}

var server = http.createServer(function (req, res) {
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    res.writeHead(405, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('Method Not Allowed');
    return;
  }

  var target = resolvePath(req.url || '/');
  if (!target) {
    res.writeHead(400, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('Bad Request');
    return;
  }

  fs.stat(target, function (err, stat) {
    if (!err && stat.isFile()) {
      sendFile(req, res, target);
      return;
    }

    if (!err && stat.isDirectory()) {
      var indexFile = path.join(target, 'index.html');
      if (fs.existsSync(indexFile)) {
        sendFile(req, res, indexFile);
        return;
      }
    }

    if (fs.existsSync(layout)) {
      sendFile(req, res, layout);
      return;
    }

    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('Not Found');
  });
});

server.listen(port, hostname, function () {
  console.log('Server listening on http://' + hostname + ':' + port);
});
`;

await rm(standaloneDir, { recursive: true, force: true });
await mkdir(standaloneDir, { recursive: true });
await cp(distDir, standaloneDist, { recursive: true });
await writeFile(resolve(standaloneDir, 'server.js'), serverSource, 'utf8');
await writeFile(
  resolve(standaloneDir, 'package.json'),
  `${JSON.stringify({ name: 'personal-site-standalone', private: true, type: 'commonjs' }, null, 2)}\n`,
  'utf8',
);

// Keep a reference so the asset copy is always validated.
await readFile(resolve(standaloneDist, 'index.html'));

console.log(`Standalone bundle ready at ${standaloneDir}`);
